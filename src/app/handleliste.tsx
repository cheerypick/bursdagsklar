import { useState } from 'react';
import { Pressable, TextInput, View } from 'react-native';
import { Redirect, useRouter } from 'expo-router';
import { useParty } from '../state/PartyProvider';
import { Loading } from '../features/Loading';
import { shareList } from '../features/share';
import { Button, CheckBox, ConfirmDialog, Icon, Screen, Surface, Text, TopBar, useToast } from '../ui';
import { fonts, radii, useColors, useLayout, themedStyles } from '../theme';
import { useTranslation } from 'react-i18next';
import { CUSTOM_ITEM_MAX, handleliste, shareText, type ShopGroup, type ShopItem } from '../core';

/**
 * Handleliste (from the Handleliste card on Planen, and the «Handle …» to-dos). Everything to buy,
 * generated by src/core (rules/shopping.ts) from the party: the included Mat lines, drinks and fruit,
 * the party things and candy for the goodie bags (opt-out). Grouped by store section; tap a row when it
 * is in the basket (ticked rows are struck through and move to the bottom of their group). Ticks and her
 * own items are saved on the party by stable id. «Del listen» shares the not-yet-bought items as plain text.
 */
export default function HandlelisteScreen() {
  const { t } = useTranslation();
  const styles = useStyles();
  const colors = useColors();
  const { ready, party, setTick, clearTicks, addCustomItem, removeCustomItem, setGoodieBagItem } = useParty();
  const router = useRouter();
  const toast = useToast();
  const { isWide, gutter } = useLayout();
  const [draft, setDraft] = useState('');
  const [confirmClear, setConfirmClear] = useState(false);
  // built on every render (cheap): the words follow the language, the items follow the party
  const list = party ? handleliste(party) : null;

  if (!ready) return <Loading />;
  if (!party || !list) return <Redirect href="/" />;

  const back = () => (router.canGoBack() ? router.back() : router.navigate('/plan'));
  const add = () => {
    if (!draft.trim()) return;
    addCustomItem(draft);
    setDraft('');
    toast(t('shopping.added'));
  };
  const share = async () => {
    const outcome = await shareList(list.title, shareText(list));
    if (outcome === 'copied') toast(t('shopping.copied'));
    else if (outcome === 'failed') toast(t('shopping.shareFailed'));
  };

  const groupCard = (g: ShopGroup) => (
    <Surface key={g.id} testID={`shop-group-${g.id}`} style={{ paddingVertical: 8 }}>
      <Text variant="eyebrow" style={{ marginTop: 8, marginBottom: 2 }}>
        {g.title}
      </Text>
      {g.items.map((i, n) => (
        <Row
          key={i.id}
          item={i}
          first={n === 0}
          onToggle={() => setTick(i.id, !i.ticked)}
          onDelete={i.custom ? () => removeCustomItem(i.id) : undefined}
        />
      ))}
      {g.id === 'godteposer' ? (
        <View style={styles.suggest} testID="shopping-goodie-suggestions">
          <Text style={styles.suggestTitle}>{t('shopping.suggestTitle')}</Text>
          <Text variant="small" style={{ marginBottom: 10 }}>
            {t('shopping.suggestLede')}
          </Text>
          <View style={styles.chips}>
            {list.goodieBagSuggestions.map((sug) => (
              <Pressable
                key={sug.id}
                testID={`goodie-${sug.id}`}
                accessibilityRole="button"
                accessibilityLabel={
                  sug.picked
                    ? t('shopping.suggestRemove', { item: sug.label.toLowerCase() })
                    : t('shopping.suggestAdd', { item: sug.label.toLowerCase() })
                }
                accessibilityState={{ selected: sug.picked }}
                aria-pressed={sug.picked}
                onPress={() => setGoodieBagItem(sug.id, !sug.picked)}
                style={({ pressed }) => [styles.chip, sug.picked && styles.chipOn, pressed && { opacity: 0.8 }]}
              >
                <Icon
                  name={sug.picked ? 'check' : 'plus'}
                  size={16}
                  strokeWidth={2.6}
                  color={sug.picked ? colors.onPrimary : colors.green}
                />
                <Text style={[styles.chipText, sug.picked && { color: colors.onPrimary }]}>{sug.label}</Text>
              </Pressable>
            ))}
          </View>
          <Text variant="small" style={{ marginTop: 10 }} testID="shopping-healthier">
            {t('shopping.healthier')}
          </Text>
        </View>
      ) : null}
    </Surface>
  );

  // two columns of groups from 768 px, balanced by rows (deterministic: each group goes to the shorter column)
  const columns: ShopGroup[][] = [[], []];
  if (isWide) {
    const h = [0, 0];
    for (const g of list.groups) {
      const c = h[0] <= h[1] ? 0 : 1;
      columns[c].push(g);
      h[c] += g.items.length + 2;
    }
  }

  const addBox = (
    <Surface testID="shopping-add-box">
      <Text style={styles.addTitle} nativeID="shopping-add-label">
        {t('shopping.add')}
      </Text>
      <View style={styles.addRow}>
        <TextInput
          testID="shopping-add-input"
          value={draft}
          onChangeText={setDraft}
          onSubmitEditing={add}
          placeholder={t('shopping.addPlaceholder')}
          placeholderTextColor={colors.muted}
          accessibilityLabel={t('shopping.add')}
          aria-labelledby="shopping-add-label"
          maxLength={CUSTOM_ITEM_MAX}
          returnKeyType="done"
          blurOnSubmit={false}
          style={styles.input}
        />
        <Pressable
          testID="shopping-add"
          accessibilityRole="button"
          accessibilityLabel={t('shopping.add')}
          accessibilityState={{ disabled: !draft.trim() }}
          onPress={add}
          style={({ pressed }) => [styles.addBtn, !draft.trim() && { opacity: 0.5 }, pressed && { opacity: 0.8 }]}
        >
          <Icon name="plus" size={22} color={colors.onPrimary} strokeWidth={2.6} />
          <Text style={styles.addBtnText}>{t('shopping.addButton')}</Text>
        </Pressable>
      </View>
    </Surface>
  );

  const allBought = list.count > 0 && list.tickedCount >= list.count;

  return (
    <Screen tab="plan" testID="screen-shopping">
      {!isWide ? <TopBar onBack={back} /> : null}
      <View style={{ paddingHorizontal: gutter, paddingTop: isWide ? 28 : 10 }}>
        <Text variant="eyebrow">{list.title.replace(/^Handleliste – /, '')}</Text>
        <Text variant={isWide ? 'h1' : 'h1Small'} style={{ marginTop: 6, marginBottom: 8 }}>
          {t('shopping.title')}
        </Text>
        <Text variant="lede" style={{ marginBottom: 6, maxWidth: 640 }}>
          {t('shopping.lede')}
        </Text>
        <Text style={styles.progress} testID="shopping-progress">
          {allBought ? t('shopping.allBought') : t('shopping.ticked', { n: list.tickedCount, of: list.count })}
        </Text>
        <View style={{ marginTop: 16 }}>
          <Button
            testID="shopping-share"
            label={t('shopping.share')}
            accessibilityLabel={t('shopping.shareLabel')}
            onPress={share}
          />
        </View>
        {!list.menuChosen ? (
          <Surface testID="shopping-no-menu" style={{ marginTop: 16, backgroundColor: colors.butter }}>
            <Text style={{ fontFamily: fonts.bodySemi, fontSize: 16, color: colors.ink }}>{t('shopping.noMenu')}</Text>
            <View style={{ marginTop: 12 }}>
              <Button compact kind="light" label={t('shopping.toMat')} onPress={() => router.push('/mat')} />
            </View>
          </Surface>
        ) : null}
      </View>

      {isWide ? (
        <View
          style={{ flexDirection: 'row', gap: 20, paddingHorizontal: gutter, marginTop: 22, alignItems: 'flex-start' }}
        >
          {columns.map((col, c) => (
            <View key={c} style={{ flex: 1, gap: 20 }} testID={`shopping-column-${c}`}>
              {col.map(groupCard)}
              {c === 1 || columns[1].length === 0 ? addBox : null}
            </View>
          ))}
        </View>
      ) : (
        <View style={{ paddingHorizontal: gutter, marginTop: 22, gap: 16 }}>
          {list.groups.map(groupCard)}
          {addBox}
        </View>
      )}

      <View
        style={{ paddingHorizontal: gutter, marginTop: 24, gap: 12, alignItems: isWide ? 'flex-start' : 'stretch' }}
      >
        {list.tickedCount > 0 ? (
          <Pressable
            testID="shopping-clear"
            accessibilityRole="button"
            accessibilityLabel={t('shopping.clearTicks')}
            onPress={() => setConfirmClear(true)}
            style={({ pressed }) => [styles.clear, pressed && { opacity: 0.7 }]}
          >
            <Icon name="reset" size={18} color={colors.muted} strokeWidth={2.2} />
            <Text style={styles.clearText}>{t('shopping.clearTicks')}</Text>
          </Pressable>
        ) : null}
        <Button
          kind="light"
          label={t('shopping.backToPlan')}
          onPress={() => router.navigate('/plan')}
          testID="shopping-back"
        />
      </View>

      <ConfirmDialog
        visible={confirmClear}
        testID="shopping-clear-dialog"
        title={t('shopping.clearTitle')}
        message={t('shopping.clearMessage')}
        confirmLabel={t('shopping.clearConfirm')}
        cancelLabel={t('shopping.clearCancel')}
        onConfirm={() => {
          clearTicks();
          setConfirmClear(false);
        }}
        onCancel={() => setConfirmClear(false)}
      />
    </Screen>
  );
}

/** One item: a big checkbox row. Tap anywhere on it to tick it off (struck through) or back. */
function Row({
  item,
  first,
  onToggle,
  onDelete,
}: {
  item: ShopItem;
  first: boolean;
  onToggle: () => void;
  onDelete?: () => void;
}) {
  const { t } = useTranslation();
  const styles = useStyles();
  const colors = useColors();
  const on = item.ticked;
  const label = [item.name, item.qty, item.detail].filter(Boolean).join(', ');
  return (
    <View style={[styles.rowWrap, !first && styles.rowBorder]}>
      <Pressable
        testID={`shop-item-${item.id}`}
        accessibilityRole="checkbox"
        accessibilityState={{ checked: on }}
        aria-checked={on}
        accessibilityLabel={label}
        onPress={onToggle}
        style={({ pressed }) => [styles.row, pressed && { opacity: 0.7 }]}
      >
        <CheckBox checked={on} size={30} />
        <View style={[{ flex: 1 }, on && styles.off]}>
          <Text style={[styles.name, on && styles.struck]}>{item.name}</Text>
          {item.detail ? (
            <Text variant="small" style={[{ marginTop: 2 }, on && styles.struck]}>
              {item.detail}
            </Text>
          ) : null}
        </View>
        {item.qty ? (
          <Text style={[styles.qty, on && styles.off, on && styles.struck]} testID={`shop-qty-${item.id}`}>
            {item.qty}
          </Text>
        ) : null}
      </Pressable>
      {onDelete ? (
        <Pressable
          testID={`shop-delete-${item.id}`}
          accessibilityRole="button"
          accessibilityLabel={t('shopping.delete', { item: item.name })}
          onPress={onDelete}
          hitSlop={4}
          style={({ pressed }) => [styles.delete, pressed && { opacity: 0.6 }]}
        >
          <Icon name="close" size={20} color={colors.muted} strokeWidth={2.4} />
        </Pressable>
      ) : null}
    </View>
  );
}

